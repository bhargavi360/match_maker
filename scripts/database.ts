import fs from "node:fs";
import path from "node:path";
import { spawnSync } from "node:child_process";
import nextEnv from "@next/env";
const { loadEnvConfig } = nextEnv;
import { databasePath } from "../src/server/config";
loadEnvConfig(process.cwd());
const file = databasePath();
const directory = path.dirname(file);
const marker = path.join(directory, "matchmaker-owner.json");
const expected = "matchmaker-ai-rebuild-stage4";
if (fs.existsSync(file) && (!fs.existsSync(marker) || JSON.parse(fs.readFileSync(marker, "utf8")).owner !== expected)) throw new Error("Existing database ownership is unclear. No migration was run.");
if (fs.existsSync(marker) && JSON.parse(fs.readFileSync(marker, "utf8")).owner !== expected) throw new Error("Data directory belongs to another application.");
fs.mkdirSync(directory, { recursive: true });
if (!fs.existsSync(marker)) fs.writeFileSync(marker, JSON.stringify({ owner: expected }), { flag: "wx", mode: 0o600 });
console.log("Migrating only the owned rebuild database: " + file);
if (!fs.existsSync(file)) fs.writeFileSync(file, Buffer.alloc(0), { flag: "wx", mode: 0o600 });
const result = spawnSync(process.execPath, ["node_modules/prisma/build/index.js", "migrate", "deploy", "--config", "prisma7.config.ts"], { stdio: "inherit", env: process.env });
process.exitCode = result.status ?? 1;
